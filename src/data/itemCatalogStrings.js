export function localizeCatalogName(name, language) {
  const index = LOCALE_INDEX[language];
  if (index === undefined || !name) return name;
  if (Object.hasOwn(NAMES, name)) return NAMES[name][index];
  const robot = name.match(/^(Mister Handy|Protectron|Assaultron|Robobrain|Sentry Bot) (Torso|Head|Arm|Legs|Treads|Thruster|Eye Stalk)$/);
  if (robot) return `${ROBOT_PARTS[robot[2]][index]} ${ROBOT_MODELS[robot[1]][index]}`;
  return name;
}

export function localizeCatalogEffect(name, effect, language) {
  return effect ? EFFECTS[name]?.[LOCALE_INDEX[language]] || effect : effect;
}

export function localizeInventoryMetadata(value, language) {
  const index = LOCALE_INDEX[language];
  if (index === undefined || value == null) return value;
  const text = String(value);
  const words = {
    yes: ["Да", "Так", "Tak"], no: ["Нет", "Ні", "Nie"],
    instant: ["Мгновенно", "Миттєво", "Natychmiast"],
    lasting: ["Длительный", "Тривалий", "Długotrwały"],
    scene: ["Сцена", "Сцена", "Scena"],
    "one scene": ["Одна сцена", "Одна сцена", "Jedna scena"],
    "until end of scene": ["До конца сцены", "До кінця сцени", "Do końca sceny"],
    "end of next scene": ["До конца следующей сцены", "До кінця наступної сцени", "Do końca następnej sceny"],
    common: ["Обычный", "Звичайний", "Pospolity"],
    uncommon: ["Необычный", "Незвичайний", "Niepospolity"],
    rare: ["Редкий", "Рідкісний", "Rzadki"],
    unique: ["Уникальный", "Унікальний", "Unikatowy"],
  };
  const label = words[text.toLowerCase()]?.[index];
  if (label) return label;
  const duration = text.match(/^(\d+)\s+(hours?|minutes?|rounds?)$/i);
  if (duration) {
    const unit = duration[2].toLowerCase().replace(/s$/, "");
    const labels = { hour: ["ч", "год", "godz."], minute: ["мин", "хв", "min"], round: ["раунд.", "раунд.", "rund."] };
    return `${duration[1]} ${labels[unit][index]}`;
  }
  return value;
}
