function titleFromId(id = "") {
  return String(id)
    .replace(/^(?:fo1|fo2|fo3|fnv)_/, "")
    .split("_")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

export function getLocationWikiMeta(location) {
  if (!location?.id) return null;
  const wikiTitle = WIKI_TITLE_BY_ID[location.id] || location.name || titleFromId(location.id);
  if (!wikiTitle) return null;
  return {
    id: location.id,
    wikiTitle,
    coreLore: CORE_LORE_BY_ID[location.id] || null,
    sourceUrl: `https://fallout.fandom.com/wiki/${encodeURIComponent(wikiTitle.replaceAll(" ", "_"))}`,
  };
}

export function getLocationCoreLore(location) {
  const meta = getLocationWikiMeta(location);
  if (!meta) return null;
  return {
    source: "Fallout Wiki",
    wikiTitle: meta.wikiTitle,
    summary: meta.coreLore,
  };
}
