export function localizeRecipeGroup(group, language) {
  const index = LOCALE_INDEX[language];
  if (index === undefined) return group;
  const label = GROUPS[group]?.[index];
  if (label) return label;
  const weapon = group?.replace(/ MODS?$/, "");
  const weaponName = WEAPON_GROUPS[weapon]?.[index];
  if (!weaponName) return group;
  return `${["Моды", "Моди", "Mody"][index]} · ${weaponName}`;
}

export function localizeRecipeTerm(name, language) {
  const index = LOCALE_INDEX[language];
  if (index === undefined) return name;
  const capacitor = name?.match(/^Capacitor (Mk [IVX]+)$/);
  if (capacitor) return `${["Конденсатор", "Конденсатор", "Kondensator"][index]} ${capacitor[1]}`;
  return NAMES[name]?.[index] || name;
}

export function localizeRecipeQualifier(name, language) {
  const index = LOCALE_INDEX[language];
  return QUALIFIERS[name]?.[index] || WEAPON_GROUPS[name?.toUpperCase()]?.[index] || name;
}
