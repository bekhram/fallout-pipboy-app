export function normalizeGmLanguage(language) {
  const code = String(language || "en")
    .toLowerCase()
    .split("-")[0];
  return GM_MENU_COPY[code] ? code : "en";
}

export function gmMenuText(language) {
  return GM_MENU_COPY[normalizeGmLanguage(language)] || GM_MENU_COPY.en;
}

export function interpolateGmText(template, values = {}) {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{{${key}}}`, String(value)),
    String(template || "")
  );
}
